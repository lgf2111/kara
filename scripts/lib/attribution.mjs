/**
 * Kara's history records what changed, not which tools typed it. These
 * patterns catch claims of authorship: co-authorship trailers, "generated
 * by/with" credits, and tool signatures.
 *
 * They deliberately do not catch a tool or vendor name on its own. Naming an
 * upstream model or its licence is ordinary technical writing: "upstream
 * openai/whisper weights MIT" and "monteslu/htdemucs-web-onnx, MIT" are facts
 * this project needs to record, not credits for having written the code. Only
 * the authorship context makes a mention a violation.
 *
 * They are also word-bounded, because a bare "ai" matches "fail", "main" and
 * "available", and a bare "generated" matches the ffmpeg-generated fixtures
 * this project relies on.
 *
 * @typedef {object} AttributionPattern
 * @property {string} id
 * @property {RegExp} pattern
 */

/** Tools and vendors, only ever matched next to an authorship verb. */
const TOOL = String.raw`(?:ai|llm|chatgpt|claude|copilot|gemini|codex|cursor|anthropic|openai|deepmind|assistant|agent|bot|language\s+model|gpt-?\d\S*)`;

/** @type {readonly AttributionPattern[]} */
export const ATTRIBUTION_PATTERNS = [
  // Co-authorship trailer, the usual way a tool signs a commit.
  { id: 'co-authored-by', pattern: /co-?authored-by\s*:/i },
  // "generated by an agent", "written with Claude", "produced using GPT-5".
  {
    id: 'authored-by-tool',
    pattern: new RegExp(
      String.raw`\b(?:generated|written|authored|created|produced|implemented|refactored|committed)\s+(?:by|with|using)\s+(?:an?\s+|the\s+)?${TOOL}\b`,
      'i',
    ),
  },
  // "assisted by an LLM", "paired with Copilot".
  {
    id: 'assisted-by-tool',
    pattern: new RegExp(String.raw`\b(?:assisted|paired|co-?written)\s+(?:by|with)\s+(?:an?\s+|the\s+)?${TOOL}\b`, 'i'),
  },
  // The hyphenated adjective: "AI-generated patch", "LLM-authored tests".
  {
    id: 'machine-authored',
    pattern: /\b(?:ai|llm)[-\s](?:generated|written|authored|assisted|made)\b/i,
  },
  // "on behalf of an AI", "courtesy of ChatGPT".
  {
    id: 'credited-tool',
    pattern: new RegExp(String.raw`\b(?:courtesy\s+of|on\s+behalf\s+of|thanks\s+to)\s+(?:an?\s+|the\s+)?${TOOL}\b`, 'i'),
  },
  // A signature marker rather than a sentence.
  { id: 'robot-emoji', pattern: /\u{1F916}/u },
];

/**
 * Paths skipped by the file-content scan. Short by design, each with a reason:
 *
 * - this module and its test: they hold the pattern list and the strings that
 *   exercise it, so they match by construction.
 *
 * @type {readonly string[]}
 */
export const CONTENT_SCAN_EXCLUSIONS = [
  'scripts/lib/attribution.mjs',
  'scripts/lib/attribution.test.mjs',
];

/**
 * @param {string} filePath repository-relative path
 * @returns {boolean}
 */
export function isExcludedFromContentScan(filePath) {
  return CONTENT_SCAN_EXCLUSIONS.includes(filePath);
}

/**
 * @typedef {object} Finding
 * @property {string} id which pattern matched
 * @property {number} line 1-based line of the first matching line, 0 if the
 *   match spans a line break
 * @property {string} excerpt
 */

/**
 * @param {string} text
 * @returns {Finding[]}
 */
export function findAttribution(text) {
  /** @type {Finding[]} */
  const findings = [];
  const lines = text.split('\n');
  for (const { id, pattern } of ATTRIBUTION_PATTERNS) {
    if (!pattern.test(text)) {
      continue;
    }
    const index = lines.findIndex((line) => pattern.test(line));
    findings.push({
      id,
      line: index + 1,
      excerpt: index === -1 ? '' : (lines[index] ?? '').trim().slice(0, 120),
    });
  }
  return findings;
}
