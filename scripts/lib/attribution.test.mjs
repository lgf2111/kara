import { describe, expect, it } from 'vitest';

import { CONTENT_SCAN_EXCLUSIONS, findAttribution } from './attribution.mjs';

/**
 * @param {string} text
 * @returns {string[]}
 */
function ids(text) {
  return findAttribution(text).map((finding) => finding.id);
}

describe('findAttribution', () => {
  it('flags co-authorship trailers whatever the casing', () => {
    expect(ids('feat: add player\n\nCo-Authored-By: Someone <someone@example.com>')).toContain('co-authored-by');
    expect(ids('co-authored-by: someone')).toContain('co-authored-by');
    expect(ids('Co-authored-By: someone')).toContain('co-authored-by');
  });

  it('flags assistant and vendor names', () => {
    expect(ids('written with Claude')).toContain('assistant-name');
    expect(ids('ask Kiro to refactor')).toContain('assistant-name');
    expect(ids('// courtesy of ChatGPT')).toContain('assistant-name');
    expect(ids('anthropic.com')).toContain('vendor-name');
    expect(ids('powered by GPT-4')).toContain('model-version');
  });

  it('flags generic machine-authorship claims and the robot emoji', () => {
    expect(ids('Generated by an agent')).toContain('generated-by-tool');
    expect(ids('AI-generated patch')).toContain('machine-authored');
    expect(ids('paired with an AI assistant')).toContain('machine-actor');
    expect(ids('summarised by an LLM')).toContain('llm');
    expect(ids('\u{1F916} automated commit')).toContain('robot-emoji');
  });

  it('leaves ordinary English alone', () => {
    const innocent = [
      'fix: the main vocal fails when the chain is available',
      'fixtures are generated by ffmpeg, never downloaded',
      'wait for the model weights to finish caching',
      'Cantonese leans on pasted lyrics',
      'raise the gain on the guide vocal',
      'retain the AIFF decoder path',
    ];
    for (const line of innocent) {
      expect(findAttribution(line), line).toEqual([]);
    }
  });

  it('reports the line of the first match', () => {
    const findings = findAttribution('feat: add relay\n\nbody text\nCo-authored-by: someone');
    expect(findings).toEqual([{ id: 'co-authored-by', line: 4, excerpt: 'Co-authored-by: someone' }]);
  });

  it('reports line 0 when a match spans a line break', () => {
    const findings = findAttribution('this was generated\nby an agent');
    expect(findings).toEqual([{ id: 'generated-by-tool', line: 0, excerpt: '' }]);
  });
});

describe('CONTENT_SCAN_EXCLUSIONS', () => {
  it('stays limited to the files that unavoidably contain the patterns', () => {
    expect([...CONTENT_SCAN_EXCLUSIONS].sort()).toEqual([
      'CLAUDE.md',
      'pnpm-lock.yaml',
      'scripts/lib/attribution.mjs',
      'scripts/lib/attribution.test.mjs',
    ]);
  });
});
