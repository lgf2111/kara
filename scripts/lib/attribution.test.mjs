import { describe, expect, it } from 'vitest';

import { CONTENT_SCAN_EXCLUSIONS, findAttribution } from './attribution.mjs';

/**
 * @param {string} text
 * @returns {string[]}
 */
function ids(text) {
  return findAttribution(text).map((finding) => finding.id);
}

describe('findAttribution', () => {
  it('flags co-authorship trailers whatever the casing', () => {
    expect(ids('feat: add player\n\nCo-Authored-By: Someone <someone@example.com>')).toContain('co-authored-by');
    expect(ids('co-authored-by: someone')).toContain('co-authored-by');
    expect(ids('Co-authored-By: someone')).toContain('co-authored-by');
  });

  it('flags authorship credited to a tool', () => {
    expect(ids('written with Claude')).toContain('authored-by-tool');
    expect(ids('Generated by an agent')).toContain('authored-by-tool');
    expect(ids('implemented using ChatGPT')).toContain('authored-by-tool');
    expect(ids('produced with GPT-5')).toContain('authored-by-tool');
    expect(ids('refactored by Copilot')).toContain('authored-by-tool');
    expect(ids('created with the assistant')).toContain('authored-by-tool');
  });

  it('flags assistance and credit phrasing', () => {
    expect(ids('paired with an AI')).toContain('assisted-by-tool');
    expect(ids('assisted by an LLM')).toContain('assisted-by-tool');
    expect(ids('courtesy of ChatGPT')).toContain('credited-tool');
    expect(ids('thanks to Gemini')).toContain('credited-tool');
  });

  it('flags the hyphenated adjective and the signature emoji', () => {
    expect(ids('AI-generated patch')).toContain('machine-authored');
    expect(ids('LLM-authored tests')).toContain('machine-authored');
    expect(ids('\u{1F916} automated commit')).toContain('robot-emoji');
  });

  it('leaves ordinary English alone', () => {
    const innocent = [
      'fix: the main vocal fails when the chain is available',
      'fixtures are generated by ffmpeg, never downloaded',
      'wait for the model weights to finish caching',
      'Cantonese leans on pasted lyrics',
      'raise the gain on the guide vocal',
      'retain the AIFF decoder path',
      'the agent handles retries',
    ];
    for (const line of innocent) {
      expect(findAttribution(line), line).toEqual([]);
    }
  });

  it('leaves licence notes and upstream model names alone', () => {
    const legitimate = [
      'Apache-2.0 (ONNX repo); upstream openai/whisper weights MIT',
      'monteslu/htdemucs-web-onnx, licence MIT, credits Defossez et al.',
      'raydotac/AudioSeparatorONNX: MIT for the conversion',
      'whisper-base int8 encoder and merged decoder',
      'the UVR MDX-Net weights come from Anjok07',
      'htdemucs is from Meta AI research',
      'Behavioral guidelines to reduce common LLM coding mistakes.',
      'transcription uses a Whisper-family model via onnxruntime-web',
    ];
    for (const line of legitimate) {
      expect(findAttribution(line), line).toEqual([]);
    }
  });

  it('reports the line of the first match', () => {
    const findings = findAttribution('feat: add relay\n\nbody text\nCo-authored-by: someone');
    expect(findings).toEqual([{ id: 'co-authored-by', line: 4, excerpt: 'Co-authored-by: someone' }]);
  });

  it('reports line 0 when a match spans a line break', () => {
    const findings = findAttribution('this was generated\nby an agent');
    expect(findings).toEqual([{ id: 'authored-by-tool', line: 0, excerpt: '' }]);
  });
});

describe('CONTENT_SCAN_EXCLUSIONS', () => {
  it('stays limited to the files that unavoidably contain the patterns', () => {
    expect([...CONTENT_SCAN_EXCLUSIONS].sort()).toEqual([
      'scripts/lib/attribution.mjs',
      'scripts/lib/attribution.test.mjs',
    ]);
  });
});
